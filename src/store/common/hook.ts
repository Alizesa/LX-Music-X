export const useBgPic = () => {
  const [value, update] = useState(state.bgPic)
  const visible = useScreenVisible()

  useEffect(() => {
    if (!visible) return
    update(state.bgPic)
    global.state_event.on('bgPicUpdated', update)
    return () => {
      global.state_event.off('bgPicUpdated', update)
    }
  }, [visible])

  return value
}

